def dimension_keys() -> list[str]:
    return list(DIMENSIONS)


def get_dimension(key: str) -> Dimension:
    if key not in DIMENSIONS:
        raise KeyError(f"未知分析维度：{key}；已知：{list(DIMENSIONS)}")
    return DIMENSIONS[key]


def render_criteria(dimension: Dimension) -> str:
    """把判读要点渲染成 prompt 里的清单文本。"""
    return "\n".join(
        f"{i}. 【{name}】{detail}" for i, (name, detail) in enumerate(dimension.criteria, 1)
    )
