# 调度顺序：supervisor 按此顺序把四个维度依次派给分析师
DIMENSION_ORDER: tuple[str, ...] = (
    "business_model",
    "management",
    "capital_return",
    "margin_of_safety",
)

# 报告 / CLI 里小标题用的序号
_ORDINALS: tuple[str, ...] = ("一", "二", "三", "四", "五", "六", "七", "八")


def dimension_title(key: str) -> str:
    """维度 key → 带序号的展示标题，如 ``三、财务状况``。

    报告、CLI、入口脚本都用它。**不要在各处再抄一份标题表**：
    那种副本迟早和这里的 label 走岔——改了名字却忘了改标题，
    界面和报告就会各叫各的。
    """
    dim = get_dimension(key)
    if key not in DIMENSION_ORDER:
        return dim.label
    index = DIMENSION_ORDER.index(key)
    if index >= len(_ORDINALS):
        return dim.label
    return f"{_ORDINALS[index]}、{dim.label}"


